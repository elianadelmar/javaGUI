    private void btnBuscar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscar1ActionPerformed

    String nombreBuscado = txtBuscar.getText().trim();

    if (nombreBuscado.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(null, "Escribe un nombre", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    String numeroEncontrado = miAgenda.buscarTelefono(nombreBuscado);

    if (numeroEncontrado != null) {
        javax.swing.JOptionPane.showMessageDialog(null, "Número: " + numeroEncontrado, "Resultado", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    } else {
        javax.swing.JOptionPane.showMessageDialog(null, "No encontrado", "Resultado", javax.swing.JOptionPane.WARNING_MESSAGE);
    }

    }//GEN-LAST:event_btnBuscar1ActionPerformed

